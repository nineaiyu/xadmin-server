"""聊天消息域实现：消息落库 / 撤回 / 历史 / 附件取件。

自 chat 门面拆出（控制单文件体量）：对外调用面 ``from message import chat as
chat_service`` 的属性访问经门面 ``__init__`` 再导出保持不变；本模块只做同步
DB 与纯函数逻辑，消息广播（channel layer）仍在 ws 层。表情回应在 ``reactions.py``、
未读游标 / 会话列表在 ``chat_sessions.py``（同批拆出）。
"""

